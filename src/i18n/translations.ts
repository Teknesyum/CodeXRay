type RuntimeReplacements = ReadonlyArray<readonly [RegExp, string]>;

let runtimeReplacements: RuntimeReplacements | null = null;
let runtimeReplacementsLoad: Promise<void> | null = null;

export const isRuntimeTextReady = (locale: Locale): boolean =>
  locale === 'en' || runtimeReplacements !== null;

export const loadRuntimeText = (locale: Locale): Promise<void> => {
  if (isRuntimeTextReady(locale)) return Promise.resolve();
  runtimeReplacementsLoad ??= import('./runtimeReplacements')
    .then((module) => {
      runtimeReplacements = module.runtimeReplacements;
    })
    .catch((error: unknown) => {
      runtimeReplacementsLoad = null;
      throw error;
    });
  return runtimeReplacementsLoad;
};

export const translateRuntimeText = (text: string, locale: Locale): string => {
  if (locale === 'en') return text;
  if (runtimeReplacements === null) {
    throw new Error(`translateRuntimeText was called for locale "${locale}" before loadRuntimeText resolved.`);
  }
  return runtimeReplacements.reduce(
    (result, [pattern, replacement]) => result.replace(pattern, replacement),
    text,
  );
};
