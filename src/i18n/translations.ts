export const t = (
  key: string,
  locale: Locale = 'en',
  values: Record<string, string | number> = {},
): string => {
  let result = dictionaries[locale][key] ?? dictionaries.en[key] ?? key;
  for (const [name, value] of Object.entries(values)) {
    result = result.replaceAll(`{${name}}`, String(value));
  }
  return result;
};

